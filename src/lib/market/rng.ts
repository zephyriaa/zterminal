/**
 * Deterministic pseudo-random utilities.
 *
 * The mock provider MUST be reproducible: the same (symbol, timeframe,
 * date range, parameters) must always produce identical bars, so that
 * backtests are deterministic.
 */

export function hashString(s: string): number {
  let h = 2166136261 >>> 0;
  for (let i = 0; i < s.length; i++) {
    h ^= s.charCodeAt(i);
    h = Math.imul(h, 16777619);
  }
  return h >>> 0;
}

/** mulberry32 — fast, deterministic PRNG. */
export function mulberry32(seed: number): () => number {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/** Standard normal via Box-Muller using a supplied uniform RNG. */
export function gaussian(rng: () => number): number {
  let u = 0, v = 0;
  while (u === 0) u = rng();
  while (v === 0) v = rng();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

/** Deterministic per-bar seed for a symbol/timeframe/globalBarIndex. */
export function barSeed(symbol: string, tf: string, globalBarIndex: number): number {
  return hashString(`${symbol}|${tf}|${globalBarIndex}`);
}
